
<?php

session_start();

require_once "db.php";

/*
|--------------------------------------------------------------------------
| CEK LOGIN
|--------------------------------------------------------------------------
*/

if (!isset($_SESSION['id_user'])) {
    header("Location: login.php");
    exit;
}


/*
|--------------------------------------------------------------------------
| AMBIL ROLE USER
|--------------------------------------------------------------------------
*/

$role = $_SESSION['role'] ?? '';


/*
|--------------------------------------------------------------------------
| ROUTER DASHBOARD BERDASARKAN ROLE
|--------------------------------------------------------------------------
*/

switch ($role) {

    /*
    |--------------------------------------------------------------------------
    | ADMIN
    |--------------------------------------------------------------------------
    */
    case 'admin':

        header("Location: dashboard_admin.php");
        exit;


    /*
    |--------------------------------------------------------------------------
    | PETUGAS
    |--------------------------------------------------------------------------
    */
    case 'petugas':

        header("Location: dashboard_petugas.php");
        exit;


    /*
    |--------------------------------------------------------------------------
    | OWNER
    |--------------------------------------------------------------------------
    */
    case 'owner':

        header("Location: dashboard_owner.php");
        exit;


    /*
    |--------------------------------------------------------------------------
    | PENGGUNA
    |--------------------------------------------------------------------------
    */
    case 'pengguna':

        header("Location: dashboard_pengguna.php");
        exit;


    /*
    |--------------------------------------------------------------------------
    | KARYAWAN RUMAH SAKIT
    |--------------------------------------------------------------------------
    */
    case 'karyawan':

        header("Location: dashboard_karyawan.php");
        exit;


    /*
    |--------------------------------------------------------------------------
    | ROLE TIDAK VALID
    |--------------------------------------------------------------------------
    */
    default:

        session_unset();
        session_destroy();

        header("Location: login.php");
        exit;
}
